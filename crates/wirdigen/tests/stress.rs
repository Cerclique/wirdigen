//! Stress Protocol Descriptions (#216): the workload of `make profile` and `make profile-mem`,
//! committed in `tests/stress/` so profiles before and after a change are comparable.
//!
//! Each file is generated here with plain deterministic Rust, a different shape each: wide (many
//! Types, Fields and Enums), deep (at the Field and Expression depth limits, and as deep in YAML
//! as a valid description goes), Expression-heavy (`if:` conditions and `switch` Fields), and
//! coverage (every feature once, at an ordinary size; checked in `src/coverage.rs`). Together they
//! take about a second to generate on the `profiling` build.
//!
//! `WIRDIGEN_BLESS=1` (`make refresh-stress`) rewrites the files. Otherwise every file must be
//! valid and match its generator byte for byte.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use wirdigen::Source;

/// The first line of every stress file.
const HEADER: &str = "# Generated by tests/stress.rs: run `make refresh-stress`, never edit by hand.\n";

/// Appends a formatted line to the description being built.
macro_rules! line {
    ($text:expr, $($arg:tt)*) => {
        writeln!($text, $($arg)*).expect("writing to a String")
    };
}

/// The Enums of the wide shape.
const WIDE_ENUMS: usize = 200;
/// The Types of the wide shape, each used once at the top level.
const WIDE_TYPES: usize = 320;
/// The Fields of each Type of the wide shape.
const WIDE_TYPE_FIELDS: usize = 40;
/// The top-level Fields of the wide shape, besides its Types.
const WIDE_TOP_FIELDS: usize = 1_500;

/// Appends Field `j` of Structure `i` of the wide shape at `indent`: the kind of Field cycles
/// with `j`, and the Enum it names with `i + j`.
fn wide_field(text: &mut String, indent: &str, i: usize, j: usize) {
    let name = format!("f{j}");
    let e = (i + j) % WIDE_ENUMS;
    match j % 10 {
        0 => line!(text, "{indent}- {{ name: {name}, type: uint8, values: E{e} }}"),
        1 => line!(text, "{indent}- {{ name: {name}, type: uint16, display: hex }}"),
        2 => line!(text, "{indent}- {{ name: {name}, type: uint32, unit: [byte, bytes] }}"),
        3 => line!(text, "{indent}- {{ name: {name}, type: int16, label: Field {j} of {i} }}"),
        4 => line!(text, "{indent}- {{ name: {name}, type: bool, true: Set, false: Clear }}"),
        5 => line!(text, "{indent}- {{ name: {name}, type: string, size: 4 }}"),
        6 => line!(text, "{indent}- {{ name: {name}, type: bytes, prefix: uint8, display: colon }}"),
        7 => line!(text, "{indent}- {{ name: {name}, type: ipv4, description: Address {j} }}"),
        8 => line!(text, "{indent}- {{ name: {name}, type: float32 }}"),
        _ => {
            line!(text, "{indent}- name: {name}");
            line!(text, "{indent}  type: uint8");
            line!(text, "{indent}  bits:");
            line!(text, "{indent}    - {{ name: a, width: 1 }}");
            line!(text, "{indent}    - {{ name: b, width: 3, values: E{e} }}");
            line!(text, "{indent}    - {{ padding: 1 }}");
            line!(text, "{indent}    - {{ name: c, width: 3, display: hex }}");
        }
    }
}

/// Many Types, Fields and Enums, each Type used once at the top level.
fn wide() -> String {
    let mut text = format!("{HEADER}# Many Types, Fields and Enums.\nname: stress_wide\nfields:\n");
    for i in 0..WIDE_TYPES {
        line!(text, "  - {{ name: t{i}, type: T{i} }}");
    }
    for j in 0..WIDE_TOP_FIELDS {
        wide_field(&mut text, "  ", WIDE_TYPES, j);
    }
    text.push_str("types:\n");
    for i in 0..WIDE_TYPES {
        line!(text, "  T{i}:\n    fields:");
        for j in 0..WIDE_TYPE_FIELDS {
            wide_field(&mut text, "      ", i, j);
        }
    }
    text.push_str("enums:\n");
    for e in 0..WIDE_ENUMS {
        line!(text, "  E{e}:");
        for key in 0..7 {
            line!(text, "    {key}: Value {key} of {e}");
        }
        line!(text, "    \"7-255\": Other");
    }
    text
}

/// The Field and Expression depth limit (ADR 0018, ADR 0020).
const DEPTH_LIMIT: usize = 64;
/// How many times the deep shape repeats each of its parts.
const DEEP_COPIES: usize = 8;

/// Fields exactly 64 deep, through a chain of Types, through inline structures and through
/// `switch` Fields, the deepest YAML a valid description reaches; Expressions exactly 64 deep.
fn deep() -> String {
    let mut text = format!(
        "{HEADER}# At the limits: Fields 64 deep, Expressions 64 deep, and as deep in YAML as a valid\n\
         # description goes (a `switch` level takes three YAML levels).\nname: stress_deep\nfields:\n"
    );
    line!(text, "  - {{ name: n, type: uint8 }}");
    for copy in 0..DEEP_COPIES {
        // A chain of Types: `x` of the last is 64 deep.
        line!(text, "  - {{ name: chain{copy}, type: C{copy}x0 }}");
        // Inline structures, `x` 64 deep.
        line!(
            text,
            "  - name: nested{copy}\n    fields: [{}{{ name: x, type: uint8 }}{}]",
            "{ name: s, fields: [".repeat(DEPTH_LIMIT - 1),
            "] }".repeat(DEPTH_LIMIT - 1)
        );
        // `switch` Fields with inline cases, the sub-Fields of a bitfield 64 deep.
        let mut indent = "  ".to_owned();
        for level in 0..DEPTH_LIMIT - 1 {
            line!(text, "{indent}- name: switch{copy}x{level}\n{indent}  switch: n\n{indent}  cases:\n{indent}    0:");
            indent.push_str("      ");
            line!(text, "{indent}- {{ name: v, type: uint8 }}");
        }
        line!(text, "{indent}- name: flags\n{indent}  type: uint8\n{indent}  bits:");
        line!(text, "{indent}    - {{ name: high, width: 4, expect: [1, \"2-3\"] }}\n{indent}    - {{ padding: 4 }}");
        // Expressions 64 deep: a flat chain, parentheses and unary operators.
        let chain = vec!["n"; DEPTH_LIMIT].join(" + ");
        line!(text, "  - {{ name: flat{copy}, type: uint8, if: \"{chain}\" }}");
        let parens = format!("{}n{}", "(".repeat(DEPTH_LIMIT - 1), ")".repeat(DEPTH_LIMIT - 1));
        line!(text, "  - {{ name: parens{copy}, type: uint8, if: \"{parens}\" }}");
        let unary = format!("{}n", "-~".repeat((DEPTH_LIMIT - 1) / 2) + "!");
        line!(text, "  - {{ name: unary{copy}, type: uint8, if: \"{unary}\" }}");
    }
    text.push_str("types:\n");
    for copy in 0..DEEP_COPIES {
        for i in 0..DEPTH_LIMIT - 1 {
            line!(
                text,
                "  C{copy}x{i}:\n    fields:\n      - {{ name: v, type: uint8 }}\n      - {{ name: next, type: C{copy}x{} }}",
                i + 1
            );
        }
        line!(text, "  C{copy}x{}:\n    fields:\n      - {{ name: x, type: uint8 }}", DEPTH_LIMIT - 1);
    }
    text
}

/// The Expression-heavy shape's size: blocks of a `switch` and conditional Fields.
const EXPRESSION_BLOCKS: usize = 460;
/// Cases of each `switch`.
const EXPRESSION_CASES: usize = 24;

/// `if:` conditions over every operator, sizes and counts computed from earlier Fields, and
/// `switch` Fields with many cases and ranges.
fn expressions() -> String {
    let mut text = format!(
        "{HEADER}# Expression-heavy: conditions, computed sizes and `switch` Fields.\nname: stress_expressions\nfields:\n"
    );
    line!(text, "  - {{ name: kind, type: uint8 }}");
    line!(
        text,
        "  - name: flags\n    type: uint16\n    bits:\n      - {{ name: a, width: 4 }}\n      - {{ name: b, width: 12 }}"
    );
    for b in 0..EXPRESSION_BLOCKS {
        line!(
            text,
            "  - {{ name: len{b}, type: uint16, if: \"kind + {b} > flags.a * 2 || flags.b & 0x{:x} != 0\" }}",
            b % 4096 + 1
        );
        line!(
            text,
            "  - name: block{b}\n    if: \"(kind << 2 | flags.a) % {} == {} && !(flags.b >= {b})\"\n    fields:",
            b % 7 + 2,
            b % 2
        );
        line!(text, "      - {{ name: tag, type: uint8 }}");
        line!(text, "      - {{ name: size, type: uint16, display: hex }}");
        line!(
            text,
            "      - {{ name: data, type: bytes, size: \"(size & 0xff) * 2 / (tag % 3 + 1) - _offset % 2 + 1\" }}"
        );
        line!(
            text,
            "      - {{ name: items, count: \"tag >> 4 ^ {}\", fields: [ {{ name: item, type: uint8 }} ] }}",
            b % 8
        );
        line!(text, "      - name: body\n        switch: \"tag * 3 + size % {} - ~kind\"\n        cases:", b % 5 + 2);
        for c in 0..EXPRESSION_CASES {
            if c % 6 == 5 {
                line!(
                    text,
                    "          \"{}-{}\": [ {{ name: r{c}, type: uint16, if: \"-size < {c}\" }} ]",
                    c * 100,
                    c * 100 + 99
                );
            } else {
                line!(
                    text,
                    "          {}: [ {{ name: c{c}, type: uint8, if: \"tag != {c} || size <= {c}\" }} ]",
                    c * 100
                );
            }
        }
        line!(text, "        default: [ {{ name: other, type: bytes, size: \"_remaining - 1 > 4 && size < 3\" }} ]");
    }
    text
}

