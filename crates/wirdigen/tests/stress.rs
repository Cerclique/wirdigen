/// Every stress file, by name, with its content.
fn files() -> [(&'static str, String); 4] {
    [
        ("coverage.wirdigen.yaml", format!("{HEADER}{COVERAGE}")),
        ("deep.wirdigen.yaml", deep()),
        ("expressions.wirdigen.yaml", expressions()),
        ("wide.wirdigen.yaml", wide()),
    ]
}

#[test]
fn the_stress_descriptions_are_valid_and_current() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/stress");
    let blessing = std::env::var_os("WIRDIGEN_BLESS").is_some_and(|v| v == "1");
    let files = files();
    for (name, generated) in &files {
        let path = dir.join(name);
        if blessing {
            fs::write(&path, generated).expect("tests/stress is writable when blessing");
        }
        let committed = fs::read_to_string(&path)
            .unwrap_or_else(|_| panic!("{} is missing: run `make refresh-stress`", path.display()));
        if let Err(diagnostics) = wirdigen::validate(&Source::new(*name, committed.as_str())) {
            panic!("{name} is invalid: {diagnostics}");
        }
        assert!(
            committed == *generated,
            "{name} differs from what tests/stress.rs generates: run `make refresh-stress`"
        );
    }
    for entry in fs::read_dir(&dir).expect("tests/stress exists") {
        let name = entry.expect("tests/stress is readable").file_name().into_string().expect("file names are UTF-8");
        assert!(files.iter().any(|(file, _)| *file == name), "tests/stress/{name} is not generated: remove it");
    }
}
